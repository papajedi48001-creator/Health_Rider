// Sections written for this role come first; the rest follow in manual order.
export function manualFor(role: UserRole): ManualSection[] {
  return [...manual].sort((left, right) => rank(left, role) - rank(right, role));
}

function rank(section: ManualSection, role: UserRole): number {
  if (section.id === 'overview' || section.id === 'login') return 0;
  if (section.id === 'faq') return 3;
  return section.roles?.includes(role) ? 1 : 2;
}
